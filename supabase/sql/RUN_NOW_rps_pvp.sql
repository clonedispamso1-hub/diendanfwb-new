-- ---------------------------------------------------------------------
-- 1) Bảng phòng
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.rps_rooms (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code            text   NOT NULL UNIQUE,
  stake           bigint NOT NULL CHECK (stake > 0),
  creator_id      uuid   NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  opponent_id     uuid            REFERENCES auth.users(id) ON DELETE SET NULL,
  status          text   NOT NULL DEFAULT 'waiting'
                  CHECK (status IN ('waiting','playing','done','cancelled')),
  creator_choice  text CHECK (creator_choice IN ('rock','paper','scissors')),
  opponent_choice text CHECK (opponent_choice IN ('rock','paper','scissors')),
  winner_id       uuid,
  is_draw         boolean NOT NULL DEFAULT false,
  prepare_ends_at timestamptz,   -- hết 10s "Chuẩn bị..."
  choose_ends_at  timestamptz,   -- hết 5s chọn tay
  created_at      timestamptz NOT NULL DEFAULT now(),
  finished_at     timestamptz
);
CREATE INDEX IF NOT EXISTS rps_rooms_status_idx  ON public.rps_rooms (status, id DESC);
CREATE INDEX IF NOT EXISTS rps_rooms_creator_idx ON public.rps_rooms (creator_id);

-- 2) Chat trong phòng
CREATE TABLE IF NOT EXISTS public.rps_messages (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_id    bigint NOT NULL REFERENCES public.rps_rooms(id) ON DELETE CASCADE,
  user_id    uuid   NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  body       text   NOT NULL CHECK (char_length(body) BETWEEN 1 AND 200),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS rps_messages_room_idx ON public.rps_messages (room_id, id DESC);

-- 3) Khán giả (heartbeat)
CREATE TABLE IF NOT EXISTS public.rps_viewers (
  room_id   bigint NOT NULL REFERENCES public.rps_rooms(id) ON DELETE CASCADE,
  user_id   uuid   NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  last_seen timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (room_id, user_id)
);

